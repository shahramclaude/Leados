import { db } from "@/db";
import * as schema from "@/db/schema";
import { ensureBaselineData } from "@/lib/seed";
import { withErrorHandling, jsonOk } from "@/lib/api";
import { evaluateScenarioActivation, runWarGame, buildCriticalPath, autoGenerateDecisionTree } from "@/lib/strategicIntel";

export const dynamic = "force-dynamic";

export const GET = withErrorHandling("strategic", async (_req, requestId) => {
  await ensureBaselineData(db);

  const metricRows = await db.select().from(schema.metrics);
  const scenarios = metricRows.map((m) =>
    evaluateScenarioActivation({ name: m.name, actual: m.baseline + m.stdDev * 2, baseline: m.baseline, stdDev: m.stdDev }),
  );

  const wargame = runWarGame(10);

  const projectRows = await db.select().from(schema.projects);
  const criticalPath = buildCriticalPath(
    projectRows.map((p) => ({ id: p.id, name: p.name, durationDays: p.durationDays, dependencies: p.dependencies })),
  );

  const decisionTree = autoGenerateDecisionTree("strategic", "How should we respond to the competitive threat?");

  return jsonOk({ scenarios, wargame, criticalPath, decisionTree }, requestId);
});
