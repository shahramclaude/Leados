import { SectionIntro, DemoNotice, Card, CardHeader, Badge, StatPill } from '../components/ui';
import { grandGateMatrix, gateSummary } from '../data/sampleData';

function statusTone(status: string) {
  if (status === 'pass') return 'pass' as const;
  if (status === 'fail') return 'fail' as const;
  if (status === 'unknown') return 'warn' as const;
  return 'neutral' as const;
}

export default function GrandGate() {
  return (
    <div className="space-y-6">
      <SectionIntro
        title="Grand gate matrix"
        description="Every gate declared across the program, re-measured — not copied from a prior run. 'Never-run' is reported honestly rather than hidden."
      />
      <DemoNotice />

      <div className="grid grid-cols-2 gap-3 sm:grid-cols-4">
        <StatPill label="Total gates" value={String(gateSummary.totalGates)} />
        <StatPill label="Pass" value={String(gateSummary.pass)} tone="pass" />
        <StatPill label="Fail" value={String(gateSummary.fail)} tone="fail" />
        <StatPill label="Never-run / unknown" value={String(gateSummary.neverRun + gateSummary.unknown)} tone="warn" />
      </div>

      <Card>
        <CardHeader eyebrow="Re-measured this run" title="Gate ledger" />
        <ul className="divide-y divide-slate-50 px-5 py-2 dark:divide-slate-800/60">
          {grandGateMatrix.map((g) => (
            <li key={g.id} className="flex flex-wrap items-start justify-between gap-3 py-3 text-sm">
              <div className="min-w-0 flex-1">
                <div className="flex items-center gap-2">
                  <span className="font-mono text-[11px] text-slate-400">Part {g.part}</span>
                  <Badge tone={statusTone(g.status)}>{g.status}</Badge>
                </div>
                <p className="mt-1 font-medium text-slate-800 dark:text-slate-100">{g.statement}</p>
                <p className="mt-0.5 text-xs text-slate-500">Accept: {g.accept}</p>
              </div>
              <div className="shrink-0 text-right text-xs text-slate-500">
                <p className="max-w-[16rem]">{g.measured}</p>
              </div>
            </li>
          ))}
        </ul>
      </Card>

      <Card className="px-5 py-4">
        <p className="text-[11px] font-semibold uppercase tracking-wide text-indigo-500">Strongest argument this is NOT ready</p>
        <p className="mt-2 text-sm text-slate-600 dark:text-slate-300">
          This console has no live backend: the Action Gate bypass fuzz test, kill-switch latency drill, fault-injection
          harness, and 30-day drift replay have never actually run against real infrastructure. Until those are wired
          up and the numbers above are regenerated by real commands, every "pass" badge in this demo should be read as
          a target, not a result.
        </p>
      </Card>
    </div>
  );
}
