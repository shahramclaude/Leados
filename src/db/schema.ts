// Leados database schema.
//
// NOTE: This repository snapshot does not contain the "Part 1-3" files the
// Part-4 task description references (eventBrain.ts, ruleEngine.ts,
// causalInference.ts, schedule.ts, and their underlying tables). To deliver a
// working Autonomous Brain Loop we recreate the minimal foundational schema
// (events, people, notifications, settings, briefings) alongside the new
// agent tables requested in this part. No destructive changes are made to
// any table that may already exist in a real deployment — this file only
// ADDS table definitions.

import {
  pgTable,
  text,
  integer,
  real,
  boolean,
  jsonb,
  timestamp,
  serial,
} from "drizzle-orm/pg-core";

// ─────────────────────────────────────────────────────────────────────────
// FOUNDATIONAL TABLES (recreated — see note above)
// ─────────────────────────────────────────────────────────────────────────

/** Raw leadership/ops events that feed the event brain. */
export const events = pgTable("events", {
  id: text("id").primaryKey(),
  type: text("type").notNull(),
  domain: text("domain").notNull(),
  personId: text("person_id"),
  entityId: text("entity_id"),
  entityType: text("entity_type"),
  severity: integer("severity").notNull().default(1),
  title: text("title"),
  payload: jsonb("payload").$type<Record<string, unknown>>(),
  occurredAt: timestamp("occurred_at", { withTimezone: true, mode: "date" })
    .notNull()
    .defaultNow(),
  createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
    .notNull()
    .defaultNow(),
});

/** People referenced by events (for human-readable hypothesis claims). */
export const people = pgTable("people", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  role: text("role"),
  team: text("team"),
  createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
    .notNull()
    .defaultNow(),
});

/** Notifications surfaced to leadership (manual + autonomous). */
export const notifications = pgTable("notifications", {
  id: serial("id").primaryKey(),
  severity: integer("severity").notNull().default(1),
  title: text("title").notNull(),
  message: text("message").notNull(),
  domain: text("domain"),
  ruleId: text("rule_id"),
  read: boolean("read").notNull().default(false),
  meta: jsonb("meta").$type<Record<string, unknown>>(),
  createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
    .notNull()
    .defaultNow(),
});

/** Generic key/value settings store (e.g. agent.lastRunAt, rule weights). */
export const settings = pgTable("settings", {
  key: text("key").primaryKey(),
  value: text("value"),
  updatedAt: timestamp("updated_at", { withTimezone: true, mode: "date" })
    .notNull()
    .defaultNow(),
});

/** Daily morning briefings generated by the autonomous agent. */
export const briefings = pgTable("briefings", {
  id: serial("id").primaryKey(),
  date: text("date").notNull().unique(),
  orgHealthScore: integer("org_health_score").notNull(),
  riskProfile: text("risk_profile").notNull(),
  executiveSummary: text("executive_summary").notNull(),
  top3Priorities: jsonb("top3_priorities").$type<unknown[]>(),
  top3Risks: jsonb("top3_risks").$type<unknown[]>(),
  decisionsNeeding48hAction: jsonb(
    "decisions_needing_48h_action",
  ).$type<unknown[]>(),
  physicsStatement: text("physics_statement").notNull(),
  uncertaintyStatement: text("uncertainty_statement").notNull(),
  hypothesesOpen: integer("hypotheses_open").notNull().default(0),
  hypothesesConfirmedThisWeek: integer("hypotheses_confirmed_this_week")
    .notNull()
    .default(0),
  createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
    .notNull()
    .defaultNow(),
});

// ─────────────────────────────────────────────────────────────────────────
// PART 4 — AUTONOMOUS BRAIN LOOP TABLES
// ─────────────────────────────────────────────────────────────────────────

/** Full audit record of every agent cycle. */
export const agentCycles = pgTable("agent_cycles", {
  id: text("id").primaryKey(),
  startedAt: timestamp("started_at", { withTimezone: true, mode: "date" }).notNull(),
  completedAt: timestamp("completed_at", { withTimezone: true, mode: "date" }),
  status: text("status").notNull(), // running|complete|partial|failed
  orgHealthScore: integer("org_health_score"),
  riskProfile: text("risk_profile"),
  criticalCount: integer("critical_count").notNull().default(0),
  cascadeCount: integer("cascade_count").notNull().default(0),
  playbooksTriggered: integer("playbooks_triggered").notNull().default(0),
  hypothesesCreated: integer("hypotheses_created").notNull().default(0),
  hypothesesResolved: integer("hypotheses_resolved").notNull().default(0),
  adaptedInterval: boolean("adapted_interval").notNull().default(false),
  totalDurationMs: integer("total_duration_ms"),
  stepDurations: jsonb("step_durations").$type<Record<string, number>>(),
  errors: jsonb("errors").$type<unknown[]>(),
  stepResults: jsonb("step_results").$type<unknown[]>(),
  // Compact snapshots so the NEXT invocation (a fresh serverless call) can
  // reconstruct `previousResult` without replaying the whole brain.
  novelFindingsSnapshot: jsonb("novel_findings_snapshot").$type<unknown[]>(),
  domainScoresSnapshot: jsonb("domain_scores_snapshot").$type<
    Record<string, number>
  >(),
});

/** Standing hypotheses the agent is tracking to resolution. */
export const hypotheses = pgTable("hypotheses", {
  id: text("id").primaryKey(),
  key: text("key").notNull(),
  entityId: text("entity_id"),
  entityType: text("entity_type"),
  ruleId: text("rule_id"),
  domain: text("domain"),
  claim: text("claim").notNull(),
  predictedAt: timestamp("predicted_at", { withTimezone: true, mode: "date" }).notNull(),
  resolveBy: timestamp("resolve_by", { withTimezone: true, mode: "date" }).notNull(),
  threshold: real("threshold"),
  metricToCheck: text("metric_to_check"),
  status: text("status").notNull().default("open"), // open|confirmed|refuted
  outcomeNote: text("outcome_note"),
  createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
    .notNull()
    .defaultNow(),
  resolvedAt: timestamp("resolved_at", { withTimezone: true, mode: "date" }),
});

/** Resolution ledger — one row per hypothesis resolution, used for Brier scoring. */
export const hypothesisResolutions = pgTable("hypothesis_resolutions", {
  id: serial("id").primaryKey(),
  hypothesisId: text("hypothesis_id").notNull(),
  ruleId: text("rule_id"),
  outcome: text("outcome").notNull(), // confirmed|refuted
  confidenceAtPrediction: real("confidence_at_prediction"),
  actualValue: real("actual_value"),
  threshold: real("threshold"),
  brierContribution: real("brier_contribution"),
  weightBefore: real("weight_before"),
  weightAfter: real("weight_after"),
  resolvedAt: timestamp("resolved_at", { withTimezone: true, mode: "date" })
    .notNull()
    .defaultNow(),
});

/** Time series of per-domain belief state, used to detect drift. */
export const beliefSnapshots = pgTable("belief_snapshots", {
  id: serial("id").primaryKey(),
  snapshotAt: timestamp("snapshot_at", { withTimezone: true, mode: "date" })
    .notNull()
    .defaultNow(),
  domain: text("domain").notNull(),
  score: real("score").notNull(),
  velocity: real("velocity").notNull(),
  posterior: real("posterior").notNull(),
  eventCount: integer("event_count").notNull().default(0),
});

/** Cycle-over-cycle deltas, consumed by the SSE / dashboard layer. */
export const agentDelta = pgTable("agent_delta", {
  id: serial("id").primaryKey(),
  cycleId: text("cycle_id").notNull(),
  createdAt: timestamp("created_at", { withTimezone: true, mode: "date" })
    .notNull()
    .defaultNow(),
  delta: jsonb("delta").$type<Record<string, unknown>>(),
  consumed: boolean("consumed").notNull().default(false),
});

/** Active/historical auto-triggered (or manual) playbook runs. */
export const playbookInstances = pgTable("playbook_instances", {
  id: serial("id").primaryKey(),
  ruleId: text("rule_id").notNull(),
  playbookId: text("playbook_id").notNull(),
  status: text("status").notNull().default("active"), // active|completed|cancelled
  source: text("source").notNull().default("autonomous_agent"),
  triggeredAt: timestamp("triggered_at", { withTimezone: true, mode: "date" })
    .notNull()
    .defaultNow(),
  assignedDomain: text("assigned_domain"),
  completedAt: timestamp("completed_at", { withTimezone: true, mode: "date" }),
  notes: text("notes"),
});
