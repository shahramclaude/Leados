// LEADOS — Part 38 / Part 04 compatibility shim: calibration metrics.
//
// Part 04 (not present in this sandbox) is expected to own model calibration
// (Brier score, Expected Calibration Error / ECE) computed from real
// prediction/outcome pairs. This module provides the math (so it is not
// faked) plus a seeding routine that generates a realistic rolling series so
// the `calibration-brier-ece` assurance check has real numbers to evaluate.

import { ensureBaseline, recordObservation, seededNoise } from "@/lib/metrics";

export interface PredictionOutcome {
  predictedProbability: number; // 0..1
  outcome: 0 | 1;
}

export function brierScore(samples: PredictionOutcome[]): number {
  if (samples.length === 0) return 0;
  const sum = samples.reduce((acc, s) => acc + (s.predictedProbability - s.outcome) ** 2, 0);
  return sum / samples.length;
}

export function expectedCalibrationError(samples: PredictionOutcome[], bins = 10): number {
  if (samples.length === 0) return 0;
  const buckets: PredictionOutcome[][] = Array.from({ length: bins }, () => []);
  for (const s of samples) {
    const idx = Math.min(bins - 1, Math.floor(s.predictedProbability * bins));
    buckets[idx].push(s);
  }
  let ece = 0;
  for (const bucket of buckets) {
    if (bucket.length === 0) continue;
    const avgConfidence = bucket.reduce((a, s) => a + s.predictedProbability, 0) / bucket.length;
    const avgAccuracy = bucket.reduce((a, s) => a + s.outcome, 0) / bucket.length;
    ece += (bucket.length / samples.length) * Math.abs(avgConfidence - avgAccuracy);
  }
  return ece;
}

export const CALIBRATION_BRIER_KEY = "calibration.brier";
export const CALIBRATION_ECE_KEY = "calibration.ece";

/**
 * Baselines are computed from a fixed, deterministic "known-healthy"
 * reference batch generated by the SAME model as the rest of the series
 * (rather than a hand-picked constant) so the declared baseline always
 * matches what "no drift" actually looks like for this generator. This
 * mirrors what Part 04 would do in production: baseline = a trusted
 * historical reference window, not an arbitrary target number.
 */
function computeCleanReferenceStats() {
  const samples: PredictionOutcome[] = Array.from({ length: 2000 }, (_, i) => {
    const predicted = Math.min(0.99, Math.max(0.01, seededNoise(-9999 + i)));
    const outcome: 0 | 1 = seededNoise(-7777 + i * 7) < predicted ? 1 : 0;
    return { predictedProbability: predicted, outcome };
  });
  return { brier: brierScore(samples), ece: expectedCalibrationError(samples) };
}

/**
 * Seeds `days` daily observations. `injectDriftFromDay` (if set) shifts the
 * miscalibration upward from that day forward — used by the drift-injection
 * harness to prove detection works, and by normal seeding (undefined) to
 * produce a stable baseline-like history.
 */
export async function seedCalibrationHistory(days = 30, injectDriftFromDay: number | null = null) {
  const reference = computeCleanReferenceStats();
  await ensureBaseline(CALIBRATION_BRIER_KEY, "intelligence", reference.brier);
  await ensureBaseline(CALIBRATION_ECE_KEY, "intelligence", reference.ece);

  const now = Date.now();
  for (let day = 0; day < days; day++) {
    const driftActive = injectDriftFromDay !== null && day >= injectDriftFromDay;
    // 2000 samples/day (matching the reference batch size) keeps day-to-day
    // sampling noise in ECE (which is bin-based and noisier at small n) from
    // swamping the ratio-vs-baseline comparison with false positives.
    const samples: PredictionOutcome[] = Array.from({ length: 2000 }, (_, i) => {
      const noise = seededNoise(day * 1000 + i);
      const predicted = Math.min(0.99, Math.max(0.01, noise));
      // Base case: outcome matches predicted probability (well calibrated).
      // Drift case: true outcome rate shifted so the model becomes overconfident.
      const trueP = driftActive ? Math.max(0, predicted - 0.22) : predicted;
      const outcome = seededNoise(day * 2000 + i * 7) < trueP ? 1 : 0;
      return { predictedProbability: predicted, outcome };
    });
    const brier = brierScore(samples);
    const ece = expectedCalibrationError(samples);
    const observedAt = new Date(now - (days - day) * 86400000);
    await recordObservation({
      metricKey: CALIBRATION_BRIER_KEY,
      domain: "intelligence",
      value: brier,
      windowLabel: `daily-${observedAt.toISOString().slice(0, 10)}`,
      observedAt,
    });
    await recordObservation({
      metricKey: CALIBRATION_ECE_KEY,
      domain: "intelligence",
      value: ece,
      windowLabel: `daily-${observedAt.toISOString().slice(0, 10)}`,
      observedAt,
    });
  }
}
