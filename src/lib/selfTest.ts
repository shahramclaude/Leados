export type TestResult = {
  name: string;
  category: string;
  passed: boolean | "skipped";
  actual: unknown;
  expected: unknown;
  durationMs: number;
  notes: string | null;
};

export type SelfTestReport = {
  passed: number;
  failed: number;
  skipped: number;
  blockers: TestResult[];
  warnings: TestResult[];
  duration: number;
  tests: TestResult[];
};

// Tests whose failure indicates degraded quality rather than a
// broken feature (statistical/approximate assertions).
const WARNING_ONLY = new Set(["MI_03_MAPE_ACCURACY_BOUNDS", "MI_04_FORECAST_METHOD_SELECTION"]);

type TestFn = () => Promise<Omit<TestResult, "durationMs" | "name" | "category">> | Omit<TestResult, "durationMs" | "name" | "category">;

async function runOne(name: string, category: string, fn: TestFn): Promise<TestResult> {
  const started = Date.now();
  try {
    const result = await fn();
    return { name, category, durationMs: Date.now() - started, ...result };
  } catch (err) {
    return {
      name,
      category,
      durationMs: Date.now() - started,
      passed: false,
      actual: err instanceof Error ? err.message : String(err),
      expected: "no exception",
      notes: "test threw an exception",
    };
  }
}

function inRange(value: number, min: number, max: number): boolean {
  return value >= min && value <= max;
}

