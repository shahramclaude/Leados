export async function runSelfTests(db: Db): Promise<SelfTestReport> {
  const overallStart = Date.now();
  const tests: TestResult[] = [];

  await ensureBaselineData(db);

  // ── BELIEF FABRIC ──────────────────────────────────────────────

  tests.push(
    await runOne("BF_01_NOISY_OR_BOUNDS", "belief_fabric", () => {
      const posteriors = computePosteriors(defaultObservables());
      const values = LATENT_NODES.map((n) => posteriors[n]);
      const allInBounds = values.every((v) => inRange(v, 0, 1));
      return {
        passed: allInBounds,
        actual: values,
        expected: "all values in [0,1]",
        notes: null,
      };
    }),
  );

  tests.push(
    await runOne("BF_02_CASCADE_RISK_SECOND_ORDER", "belief_fabric", () => {
      const posteriors = Object.fromEntries(LATENT_NODES.map((n) => [n, 0.5])) as Record<
        (typeof LATENT_NODES)[number],
        number
      >;
      const cascadeRisk = computeCascadeRisk(posteriors);
      return {
        passed: cascadeRisk > 0.5,
        actual: cascadeRisk,
        expected: "> 0.5",
        notes: "nine moderate (0.5) risks combine via noisy-OR into a much higher cascade risk",
      };
    }),
  );

  tests.push(
    await runOne("BF_03_BELIEF_DRIFT_OLS_CONSISTENCY", "belief_fabric", () => {
      const series: DriftPoint[] = Array.from({ length: 14 }, (_, i) => ({
        day: i,
        value: 0.2 + i * 0.02,
      }));
      const result = detectBeliefDrift(series);
      const passed = result.drifting === true && result.ratePerDay > 0;
      return {
        passed,
        actual: result,
        expected: "drifting=true, ratePerDay>0",
        notes: null,
      };
    }),
  );

  tests.push(
    await runOne("BF_04_BELIEF_SNAPSHOT_DEDUPLICATION", "belief_fabric", async () => {
      const entityId = 999_001;
      const snapshotAt = new Date();
      await db
        .delete(schema.beliefSnapshots)
        .where(and(eq(schema.beliefSnapshots.entityType, "test"), eq(schema.beliefSnapshots.entityId, entityId)));

      await insertBeliefSnapshotDeduped(db, { entityType: "test", entityId, node: "flightRisk", value: 0.4, snapshotAt });
      await insertBeliefSnapshotDeduped(db, {
        entityType: "test",
        entityId,
        node: "flightRisk",
        value: 0.42,
        snapshotAt: new Date(snapshotAt.getTime() + 30_000),
      });

      const rows = await db
        .select()
        .from(schema.beliefSnapshots)
        .where(and(eq(schema.beliefSnapshots.entityType, "test"), eq(schema.beliefSnapshots.entityId, entityId)));

      const passed = rows.length <= 1;

      await db
        .delete(schema.beliefSnapshots)
        .where(and(eq(schema.beliefSnapshots.entityType, "test"), eq(schema.beliefSnapshots.entityId, entityId)));

      return { passed, actual: rows.length, expected: "<= 1 row in the 60s window", notes: null };
    }),
  );

  // ── AGENT CYCLE ────────────────────────────────────────────────

  tests.push(
    await runOne("AC_01_CYCLE_COMPLETES_UNDER_15S", "agent_cycle", async () => {
      const result = await runAgentCycle(db);
      return {
        passed: result.durationMs < 15_000,
        actual: result.durationMs,
        expected: "< 15000ms",
        notes: null,
      };
    }),
  );

  tests.push(
    await runOne("AC_02_PLAYBOOK_NO_DUPLICATE_TRIGGER", "agent_cycle", async () => {
      const [playbook] = await db
        .insert(schema.playbooks)
        .values({ name: "Test dedup playbook", domain: "test_dedup", triggerCondition: "always" })
        .returning();
      const [finding] = await db
        .insert(schema.findings)
        .values({ title: "Test finding", domain: "test_dedup", severity: "high", status: "open" })
        .returning();

      try {
        await triggerPlaybookForFinding(db, playbook.id, finding.id);
        await triggerPlaybookForFinding(db, playbook.id, finding.id); // same finding again

        const instances = await db
          .select()
          .from(schema.playbookInstances)
          .where(eq(schema.playbookInstances.findingId, finding.id));

        return {
          passed: instances.length === 1,
          actual: instances.length,
          expected: 1,
          notes: null,
        };
      } finally {
        await db.delete(schema.playbookInstances).where(eq(schema.playbookInstances.findingId, finding.id));
        await db.delete(schema.findings).where(eq(schema.findings.id, finding.id));
        await db.delete(schema.playbooks).where(eq(schema.playbooks.id, playbook.id));
      }
    }),
  );

  tests.push(
    await runOne("AC_03_HYPOTHESIS_REFUTED_WEIGHT_DECREASES", "agent_cycle", async () => {
      const [rule] = await db.insert(schema.rules).values({ name: "test-rule", domain: "test", weight: 1.0 }).returning();
      const [hypothesis] = await db
        .insert(schema.hypotheses)
        .values({
          entity: "test-entity",
          claim: "test claim",
          resolveBy: new Date(),
          status: "open",
          confidence: 0.5,
          ruleId: rule.id,
        })
        .returning();

      try {
        await db.update(schema.hypotheses).set({ status: "refuted" }).where(eq(schema.hypotheses.id, hypothesis.id));
        const calibration = await calibrateRule(db, rule.id, "refuted");

        return {
          passed: calibration.after < calibration.before,
          actual: calibration.after,
          expected: `< ${calibration.before}`,
          notes: null,
        };
      } finally {
        await db.delete(schema.hypotheses).where(eq(schema.hypotheses.id, hypothesis.id));
        await db.delete(schema.rules).where(eq(schema.rules.id, rule.id));
      }
    }),
  );

  tests.push(
    await runOne("AC_04_MORNING_BRIEF_EXACTLY_3_SENTENCES", "agent_cycle", () => {
      const brief = generateMorningBrief({ openFindings: 4, criticalPeopleAtRisk: 2, cascadeRisk: 0.55 });
      const count = countSentences(brief.executiveSummary);
      return {
        passed: count === 3,
        actual: count,
        expected: 3,
        notes: brief.executiveSummary,
      };
    }),
  );

  tests.push(
    await runOne("AC_05_CALIBRATION_CLAMPS", "agent_cycle", async () => {
      const [ruleHigh] = await db.insert(schema.rules).values({ name: "clamp-high", domain: "test", weight: 2.4 }).returning();
      const [ruleLow] = await db.insert(schema.rules).values({ name: "clamp-low", domain: "test", weight: 0.12 }).returning();

      try {
        const highResult = await calibrateRule(db, ruleHigh.id, "confirmed"); // 2.4 * 1.1 = 2.64 -> must clamp to 2.5
        const lowResult = await calibrateRule(db, ruleLow.id, "refuted"); // 0.12 * 0.9 = 0.108 -> must clamp to 0.1

        const passed = highResult.after <= 2.5 && lowResult.after >= 0.1;

        return {
          passed,
          actual: { highAfter: highResult.after, lowAfter: lowResult.after },
          expected: { highAfter: "<= 2.5", lowAfter: ">= 0.1" },
          notes: null,
        };
      } finally {
        await db.delete(schema.rules).where(inArray(schema.rules.id, [ruleHigh.id, ruleLow.id]));
      }
    }),
  );

  // ── PEOPLE INTELLIGENCE ────────────────────────────────────────

  const seedPeople = buildSeedPeople(50);

  tests.push(
    await runOne("PI_01_FLIGHT_RISK_BOUNDED", "people_intel", () => {
      const scores = seedPeople.map((p) => computeFlightRisk(p));
      const passed = scores.every((s) => inRange(s, 0, 1));
      return { passed, actual: { min: Math.min(...scores), max: Math.max(...scores) }, expected: "all in [0,1]", notes: null };
    }),
  );

  tests.push(
    await runOne("PI_02_EXIT_SIGNAL_DETECTION", "people_intel", () => {
      const positive = analyzeOneOnOneNotes("The recruiter reached out to me on LinkedIn last week.");
      const negative = analyzeOneOnOneNotes("Had a great day, shipped the feature and the team is motivated.");
      const passed = positive.hasExitSignal === true && negative.hasExitSignal === false;
      return {
        passed,
        actual: { positive: positive.hasExitSignal, negative: negative.hasExitSignal },
        expected: { positive: true, negative: false },
        notes: null,
      };
    }),
  );

  tests.push(
    await runOne("PI_03_NINE_BOX_ALL_PERSONS_PLACED", "people_intel", () => {
      const placements = buildNineBox(seedPeople);
      const ids = placements.map((p) => p.personId);
      const uniqueIds = new Set(ids);
      const passed = placements.length === seedPeople.length && uniqueIds.size === seedPeople.length;
      return {
        passed,
        actual: { placed: placements.length, unique: uniqueIds.size },
        expected: { placed: seedPeople.length, unique: seedPeople.length },
        notes: null,
      };
    }),
  );

  tests.push(
    await runOne("PI_04_SUCCESSION_RISK_NO_SELF_REFERENCE", "people_intel", () => {
      const violations = seedPeople.filter((p) => computeSuccessionRisk(p, seedPeople).candidateIds.includes(p.id));
      return {
        passed: violations.length === 0,
        actual: violations.length,
        expected: 0,
        notes: null,
      };
    }),
  );

  tests.push(
    await runOne("PI_05_JACCARD_BOUNDS", "people_intel", () => {
      const identical = jaccardSimilarity(["a", "b", "c"], ["a", "b", "c"]);
      const disjoint = jaccardSimilarity(["a", "b"], ["x", "y"]);
      const partial = jaccardSimilarity(["a", "b", "c"], ["b", "c", "d"]);
      const passed = identical === 1 && disjoint === 0 && partial > 0 && partial < 1;
      return {
        passed,
        actual: { identical, disjoint, partial },
        expected: { identical: 1, disjoint: 0, partial: "(0,1)" },
        notes: null,
      };
    }),
  );

  tests.push(
    await runOne("PI_06_TEAM_CHEMISTRY_THRESHOLD", "people_intel", () => {
      const team = seedPeople.slice(0, 5).map((p, i) => ({ ...p, flightRiskScore: i < 3 ? 0.8 : 0.1 }));
      const report = buildTeamChemistryReport(team);
      const passed = report.redFlags.some((f) => f.type === "exit_cluster");
      return {
        passed,
        actual: report.redFlags.map((f) => f.type),
        expected: "contains exit_cluster",
        notes: null,
      };
    }),
  );

  // ── FINANCIAL INTELLIGENCE ─────────────────────────────────────

  tests.push(
    await runOne("FI_01_MONTE_CARLO_ORDER_STATISTICS", "financial_intel", () => {
      const result = runMonteCarloRunway({ cashBalance: 2_000_000, burnRate: 150_000, revenue: 60_000, revenueGrowth: 0.03 }, 500);
      const ordered = [result.p5, result.p10, result.p25, result.p50, result.p75, result.p90, result.p95];
      const sorted = [...ordered].sort((a, b) => a - b);
      const passed = ordered.every((v, i) => v === sorted[i]);
      return { passed, actual: ordered, expected: sorted, notes: null };
    }),
  );

  tests.push(
    await runOne("FI_02_FUNDRAISING_READINESS_SCORE_BOUNDS", "financial_intel", () => {
      const perfect = computeFundraisingReadiness({
        revenueGrowthRate: 1,
        runwayMonths: 100,
        grossMargin: 1,
        customerChurnRate: 0,
        teamCompleteness: 1,
        marketSizeScore: 1,
        existingInvestorSupport: 1,
      });
      const terrible = computeFundraisingReadiness({
        revenueGrowthRate: 0,
        runwayMonths: 0,
        grossMargin: 0,
        customerChurnRate: 1,
        teamCompleteness: 0,
        marketSizeScore: 0,
        existingInvestorSupport: 0,
      });
      const passed =
        inRange(perfect.readinessScore, 0, 100) &&
        inRange(terrible.readinessScore, 0, 100) &&
        perfect.readinessScore > terrible.readinessScore;
      return {
        passed,
        actual: { perfect: perfect.readinessScore, terrible: terrible.readinessScore },
        expected: "both in [0,100], perfect > terrible",
        notes: null,
      };
    }),
  );

  tests.push(
    await runOne("FI_03_BANKRUPTCY_PATH_DETECTION", "financial_intel", () => {
      const result = runMonteCarloRunway({ cashBalance: 100_000, burnRate: 200_000, revenue: 0, revenueGrowth: 0 }, 500);
      return {
        passed: result.p50RunwayMonths <= 1,
        actual: result.p50RunwayMonths,
        expected: "<= 1",
        notes: null,
      };
    }),
  );

  tests.push(
    await runOne("FI_04_REPRODUCIBILITY", "financial_intel", () => {
      const inputs = { cashBalance: 900_000, burnRate: 120_000, revenue: 40_000, revenueGrowth: 0.02 };
      const run1 = runMonteCarloRunway(inputs, 500, 42);
      const run2 = runMonteCarloRunway(inputs, 500, 42);
      return {
        passed: run1.p50 === run2.p50,
        actual: { run1: run1.p50, run2: run2.p50 },
        expected: "identical",
        notes: null,
      };
    }),
  );

  // ── STRATEGIC INTELLIGENCE ─────────────────────────────────────

  tests.push(
    await runOne("SI_01_SCENARIO_ACTIVATION_THRESHOLD", "strategic_intel", () => {
      const activation = evaluateScenarioActivation({ name: "churn_rate", actual: 50, baseline: 20, stdDev: 10 });
      return { passed: activation.urgency === "act", actual: activation, expected: "urgency=act", notes: null };
    }),
  );

  tests.push(
    await runOne("SI_02_WARGAME_NO_INFINITE_MOVES", "strategic_intel", () => {
      const result = runWarGame(10);
      const passed = result.completed === true && result.durationMs < 1000;
      return { passed, actual: { completed: result.completed, durationMs: result.durationMs }, expected: "completed<1000ms", notes: null };
    }),
  );

  const chainProjects: ProjectNode[] = [
    { id: 1, name: "A", durationDays: 5, dependencies: [] },
    { id: 2, name: "B", durationDays: 5, dependencies: [1] },
    { id: 3, name: "C", durationDays: 5, dependencies: [2] },
    { id: 4, name: "D", durationDays: 5, dependencies: [3] },
    { id: 5, name: "E", durationDays: 5, dependencies: [4] },
  ];

  tests.push(
    await runOne("SI_03_CRITICAL_PATH_ACYCLIC_RESULT", "strategic_intel", () => {
      const result = buildCriticalPath(chainProjects);
      const unique = new Set(result.chain);
      const passed = result.chain.length === 5 && unique.size === result.chain.length;
      return { passed, actual: result.chain, expected: "length 5, no duplicates", notes: null };
    }),
  );

  tests.push(
    await runOne("SI_04_CYCLE_DETECTION", "strategic_intel", () => {
      const cyclicProjects: ProjectNode[] = [
        { id: 1, name: "A", durationDays: 3, dependencies: [3] },
        { id: 2, name: "B", durationDays: 3, dependencies: [1] },
        { id: 3, name: "C", durationDays: 3, dependencies: [2] },
      ];
      const cycles = detectCycles(cyclicProjects);
      const flat = cycles.flat();
      const passed = cycles.length > 0 && [1, 2, 3].every((id) => flat.includes(id));
      return { passed, actual: cycles, expected: "non-empty, contains 1,2,3", notes: null };
    }),
  );

  tests.push(
    await runOne("SI_05_DECISION_TREE_BRANCHES", "strategic_intel", () => {
      const tree = autoGenerateDecisionTree("people", "Should we promote the lead engineer?");
      return {
        passed: tree.branches.length >= 2,
        actual: tree.branches.length,
        expected: ">= 2",
        notes: null,
      };
    }),
  );

  // ── METRICS INTELLIGENCE ───────────────────────────────────────

  tests.push(
    await runOne("MI_01_CUSUM_DETECTS_STRUCTURAL_BREAK", "metrics_intel", () => {
      const rng = mulberry32(99);
      const gaussian = gaussianFactory(rng);
      const series: number[] = [];
      for (let i = 0; i < 30; i++) series.push(50 + gaussian() * 5);
      for (let i = 0; i < 10; i++) series.push(80 + gaussian() * 5);
      const anomalies = runCusum(series);
      const passed = anomalies.some((a) => a.type === "structural_break" && a.index >= 28);
      return { passed, actual: anomalies, expected: "structural_break anomaly at/after index 28", notes: null };
    }),
  );

  tests.push(
    await runOne("MI_02_PEARSON_DIAGONAL", "metrics_intel", () => {
      const series = [1, 4, 9, 16, 25, 7, 3];
      const r = pearsonCorrelation(series, series);
      const passed = Number(r.toFixed(3)) === 1;
      return { passed, actual: Number(r.toFixed(3)), expected: 1, notes: null };
    }),
  );

  tests.push(
    await runOne("MI_03_MAPE_ACCURACY_BOUNDS", "metrics_intel", () => {
      const series = Array.from({ length: 20 }, (_, i) => 10 + i * 5);
      const result = runForecast(series, 5, "linear" as const);
      return { passed: result.accuracy > 80, actual: result.accuracy, expected: "> 80", notes: null };
    }),
  );

  tests.push(
    await runOne("MI_04_FORECAST_METHOD_SELECTION", "metrics_intel", () => {
      const series = Array.from({ length: 20 }, (_, i) => 10 + i * 5);
      const method = selectForecastMethod(series);
      const passed = method === "holt_winters" || (method as string) === "exponential_smoothing";
      return {
        passed,
        actual: method,
        expected: "holt_winters | exponential_smoothing (actual enum values exposed by metricsEngine.ts: moving_average | linear | exponential_smoothing | holt_winters)",
        notes: "linear is an explicit override only, never auto-selected",
      };
    }),
  );

  // ── KNOWLEDGE GRAPH ────────────────────────────────────────────

  tests.push(
    await runOne("KG_01_ROOT_CAUSE_NO_CYCLES", "knowledge_graph", () => {
      const graph: KnowledgeGraph = {
        nodes: [
          { id: 1, label: "A", domain: "ops", severity: "high", tags: [] },
          { id: 2, label: "B", domain: "ops", severity: "high", tags: [] },
        ],
        edges: [
          { fromId: 1, toId: 2, relation: "caused_by", weight: 1 },
          { fromId: 2, toId: 1, relation: "caused_by", weight: 1 },
        ],
      };
      const roots = findRootCauses(graph, 1);
      return { passed: Array.isArray(roots), actual: roots.map((r) => r.id), expected: "terminates without error", notes: null };
    }),
  );

  tests.push(
    await runOne("KG_02_JACCARD_PATTERN_MATCHING", "knowledge_graph", () => {
      const a = { id: 1, label: "A", domain: "people", severity: "high", tags: ["attrition", "flight-risk"] };
      const b = { id: 2, label: "B", domain: "people", severity: "high", tags: ["attrition", "flight-risk"] };
      const c = { id: 3, label: "C", domain: "people", severity: "high", tags: ["funding", "runway"] };
      const identicalScore = jaccardPatternMatch(a, b);
      const disjointScore = jaccardPatternMatch(a, c);
      const passed = identicalScore === 1 && disjointScore < 0.3;
      return {
        passed,
        actual: { identicalScore, disjointScore },
        expected: { identicalScore: 1, disjointScore: "< 0.3" },
        notes: null,
      };
    }),
  );

  tests.push(
    await runOne("KG_03_KNOWLEDGE_HALFLIFE_POSITIVE", "knowledge_graph", () => {
      const graph: KnowledgeGraph = {
        nodes: [{ id: 1, label: "A", domain: "ops", severity: "medium", tags: ["x"] }],
        edges: [],
      };
      const halfLife = knowledgeHalfLife(graph);
      return { passed: halfLife > 0, actual: halfLife, expected: "> 0", notes: null };
    }),
  );

  // ── EXECUTION INTELLIGENCE ─────────────────────────────────────

  tests.push(
    await runOne("EX_01_DELIVERY_CONFIDENCE_CLAMPS", "execution_intel", () => {
      const confidence = computeDeliveryConfidence({
        scopeCreepScore: 1,
        teamAttritionScore: 1,
        dependencyRiskScore: 1,
        blockerCount: 100,
        velocityTrend: -1,
      });
      return { passed: confidence >= 0, actual: confidence, expected: ">= 0", notes: null };
    }),
  );

  tests.push(
    await runOne("EX_02_BOTTLENECK_IS_IN_CRITICAL_PATH", "execution_intel", () => {
      const result = buildCriticalPath(chainProjects);
      const passed = result.bottleneckProject !== null && result.chain.includes(result.bottleneckProject);
      return { passed, actual: { bottleneck: result.bottleneckProject, chain: result.chain }, expected: "bottleneck in chain", notes: null };
    }),
  );

  tests.push(
    await runOne("EX_03_SIGMA_CLAMP_NO_NEGATIVE", "execution_intel", () => {
      const low = confidenceSigmoid(0);
      const high = confidenceSigmoid(100);
      const passed = low > 0 && low < 1 && high > 0 && high < 1;
      return { passed, actual: { low, high }, expected: "both in (0,1)", notes: null };
    }),
  );

  // ─────────────────────────────────────────────────────────────

  const duration = Date.now() - overallStart;
  const passed = tests.filter((t) => t.passed === true).length;
  const failed = tests.filter((t) => t.passed === false).length;
  const skipped = tests.filter((t) => t.passed === "skipped").length;

  const blockers = tests.filter((t) => t.passed === false && !WARNING_ONLY.has(t.name));
  const warnings = tests.filter((t) => t.passed === false && WARNING_ONLY.has(t.name));

  return { passed, failed, skipped, blockers, warnings, duration, tests };
}
