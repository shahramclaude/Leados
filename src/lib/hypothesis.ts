// The Hypothesis Engine — generates testable hypotheses from anomalies in
// the event log, tracks them against a stated test window, and summarizes
// confirmation/refutation as "organizational model updates."
//
// Original implementation written for this sandbox. It implements the
// *functional idea* described in the task's pasted "pt-V" brief
// (LEADOS.hypothesis) — nothing with that name or shape was found anywhere
// in github.com/wbweve/Leados this session (see AI-SESSION-LOG.md).

import type { HypothesisData, LeadosEvent } from './types';
import { mintId } from './store';
import {
  ageDays,
  computeDecisionVelocity,
  computeTeamEngagement,
  computeTestMetric,
  computeVelocityMean,
} from './metrics';

export interface GeneratedHypothesisResult {
  hypotheses: HypothesisData[];
  label: string;
}

export function generateFromAnomalies(events: LeadosEvent[], today: Date): GeneratedHypothesisResult {
  const hypotheses: HypothesisData[] = [];

  // --- ANOMALY 1: velocity / engagement divergence ---
  const velocity = computeVelocityMean(events, today);
  const engagement = computeTeamEngagement(events, today);
  if (velocity !== null && engagement !== null) {
    const divergence = Math.abs(velocity / 10 - engagement / 10);
    if (divergence > 0.3) {
      const highEngLowVel = engagement > velocity;
      hypotheses.push({
        id: mintId('hyp'),
        statement: highEngLowVel
          ? 'Team engagement is high but velocity is low — suggesting a process or tooling blocker, not a motivation problem.'
          : 'Velocity is high but engagement is declining — suggesting the team is burning out from overwork.',
        type: 'causal',
        source: 'metric_divergence',
        variables: [
          { name: 'velocity', currentValue: velocity },
          { name: 'engagement', currentValue: engagement },
        ],
        prediction: highEngLowVel
          ? 'Removing the process blocker will increase velocity without changing engagement (it is already high).'
          : 'If no intervention: engagement will drop below 5 within 30 days.',
        testMetric: highEngLowVel ? 'velocity' : 'team_engagement',
        testWindow_days: 30,
        confidenceAtGeneration: 0.55,
        autoGenerated: true,
        label: 'Auto-generated from velocity-engagement divergence anomaly.',
      });
    }
  }

  // --- ANOMALY 2: feedback volume without engagement lift ---
  const feedbackCount30 = events.filter((e) => e.type === 'feedback.given' && ageDays(e.ts, today) <= 30).length;
  if (feedbackCount30 >= 5 && engagement !== null && engagement < 7) {
    hypotheses.push({
      id: mintId('hyp'),
      statement:
        'High feedback volume with flat-or-low engagement suggests the feedback is not landing as intended — possibly too corrective, unclear, or not psychologically safe.',
      type: 'causal',
      source: 'feedback_engagement_paradox',
      variables: [
        { name: 'feedback_count_30d', currentValue: feedbackCount30 },
        { name: 'mean_engagement', currentValue: engagement },
      ],
      prediction: 'Shifting feedback toward more developmental framing will improve engagement within 21 days.',
      testMetric: 'team_engagement',
      testWindow_days: 21,
      confidenceAtGeneration: 0.5,
      autoGenerated: true,
      label: 'Auto-generated from feedback-engagement paradox.',
    });
  }

  // --- ANOMALY 3: decision velocity vs. evidence (overload signal) ---
  const decisionVelocity = computeDecisionVelocity(events, today);
  const openSignals = events.filter((e) => ageDays(e.ts, today) <= 30).length;
  if (decisionVelocity > 5 && openSignals > 20) {
    hypotheses.push({
      id: mintId('hyp'),
      statement:
        'High decision velocity alongside heavy recent signal volume suggests decisions may be made without full evidence. Decision quality may be declining even as volume increases.',
      type: 'predictive',
      source: 'decision_overload_signal',
      variables: [
        { name: 'decision_velocity_30d', currentValue: decisionVelocity },
        { name: 'recent_event_volume_30d', currentValue: openSignals },
      ],
      prediction: 'Decision outcomes tracked over 60 days will show a positive-resolution rate below 50%.',
      testMetric: 'decision_outcome_positive_rate',
      testWindow_days: 60,
      confidenceAtGeneration: 0.45,
      autoGenerated: true,
      label: 'Auto-generated from decision-overload signal.',
    });
  }

  // --- ANOMALY 4: conflict cluster newly concentrated on one person ---
  const recentConflicts = events.filter((e) => e.type === 'conflict.logged' && ageDays(e.ts, today) <= 14);
  const byPerson: Record<string, number> = {};
  recentConflicts.forEach((e) => {
    byPerson[e.data.person1Id] = (byPerson[e.data.person1Id] || 0) + 1;
  });
  const concentrated = Object.entries(byPerson).find(([, n]) => n >= 3);
  if (concentrated) {
    hypotheses.push({
      id: mintId('hyp'),
      statement: `Conflict events in the last 14 days are concentrated on one person (${concentrated[1]} incidents) without a matching attrition signal yet — this may be an early-warning pattern, not an established one.`,
      type: 'descriptive',
      source: 'conflict_concentration',
      variables: [{ name: 'conflict_count_14d_for_person', currentValue: concentrated[1] }],
      prediction: 'If unaddressed: an hr.attrition.logged or hr.pip.started event involving this person will occur within 30 days.',
      testMetric: 'cluster_finding_count:conflict_concentration',
      testWindow_days: 30,
      confidenceAtGeneration: 0.4,
      autoGenerated: true,
      label: 'Auto-generated from new, untagged conflict-concentration pattern.',
    });
  }

  return {
    hypotheses,
    label:
      `${hypotheses.length} hypotheses auto-generated from data anomalies. ` +
      'All require logging as hypothesis.generated events to be tracked; the system then monitors for hypothesis.result confirmation.',
  };
}

export interface OpenHypothesisStatus {
  hypothesis: HypothesisData;
  generatedTs: string;
  status: 'OPEN' | 'AWAITING_RESULT';
  daysRemaining?: number;
  currentValue?: number | null;
  note: string;
}

export function evaluateOpenHypotheses(events: LeadosEvent[], today: Date): OpenHypothesisStatus[] {
  const generated = events.filter((e) => e.type === 'hypothesis.generated');
  const resultedIds = new Set(events.filter((e) => e.type === 'hypothesis.result').map((e) => e.data.hypothesisId));
  const open = generated.filter((e) => !resultedIds.has(e.data.id));

  return open.map((hyp) => {
    const h = hyp.data as HypothesisData;
    const daysOpen = ageDays(hyp.ts, today);
    const windowExpired = daysOpen >= h.testWindow_days;

    if (!windowExpired) {
      return {
        hypothesis: h,
        generatedTs: hyp.ts,
        status: 'OPEN',
        daysRemaining: Math.ceil(h.testWindow_days - daysOpen),
        note: 'Test window not yet expired.',
      };
    }

    const currentValue = computeTestMetric(h.testMetric, events, today);
    return {
      hypothesis: h,
      generatedTs: hyp.ts,
      status: 'AWAITING_RESULT',
      currentValue,
      note: `Test window (${h.testWindow_days}d) has expired. Log a hypothesis.result event to record the outcome.`,
    };
  });
}

export interface LearningSummary {
  confirmed: number;
  refuted: number;
  total: number;
  calibration: number | null;
  confirmedLearnings: { implication: string; date: string }[];
  modelUpdates: string[];
  label: string;
}

export function learnFromResults(events: LeadosEvent[]): LearningSummary {
  const results = events.filter((e) => e.type === 'hypothesis.result');
  const confirmed = results.filter((r) => r.data.outcome === 'confirmed').length;
  const refuted = results.filter((r) => r.data.outcome === 'refuted').length;

  const autoGenHyps = events.filter((e) => e.type === 'hypothesis.generated' && e.data.autoGenerated);
  const autoConfirmed = results.filter(
    (r) => r.data.outcome === 'confirmed' && autoGenHyps.some((h) => h.data.id === r.data.hypothesisId)
  ).length;
  const calibration = autoGenHyps.length
    ? Math.round((autoConfirmed / Math.min(autoGenHyps.length, Math.max(results.length, 1))) * 100)
    : null;

  const confirmedLearnings = results
    .filter((r) => r.data.outcome === 'confirmed' && r.data.implication)
    .map((r) => ({ implication: r.data.implication as string, date: r.ts.slice(0, 10) }));

  return {
    confirmed,
    refuted,
    total: results.length,
    calibration,
    confirmedLearnings,
    modelUpdates: confirmedLearnings.map((l) => 'ORGANIZATIONAL MODEL UPDATE: ' + l.implication),
    label:
      `Hypothesis learning: ${confirmed} confirmed, ${refuted} refuted of ${results.length} resolved. ` +
      (calibration !== null ? `Auto-generation calibration: ${calibration}%.` : 'Calibration needs more resolved hypotheses.'),
  };
}
