import type { Domain, Finding } from "./types";

// ─────────────────────────────────────────────────────────────
// orgPhysics.ts — heuristic "org physics" laws.
// Every function here is explicitly a heuristic (low confidence):
// these are directional signals, not calibrated measurements.
// ─────────────────────────────────────────────────────────────

const HEURISTIC_NOTE = "heuristic (low confidence)";

function avg(xs: number[]): number {
  if (!xs.length) return 0;
  return xs.reduce((a, b) => a + b, 0) / xs.length;
}

export function clamp(n: number, lo: number, hi: number): number {
  return Math.min(hi, Math.max(lo, n));
}

/** ENTROPY — disorder across domain scores + finding churn. */
export function measureOrgEntropy(domains: Domain[], findings: Finding[]) {
  const scores = domains.map((d) => d.score);
  const mean = avg(scores);
  const variance = avg(scores.map((s) => (s - mean) ** 2));
  const findingPressure = findings.reduce((s, f) => s + f.sev / 5, 0);
  const compositeEntropy = clamp(Math.round(variance * 9 + findingPressure * 2.2), 0, 100);
  const perDomain = domains.map((d) => ({
    domain: d.key,
    entropy: clamp(Math.round(Math.abs(d.velocity) * 28 + (10 - d.score) * 3.4), 0, 100),
  }));
  return { compositeEntropy, perDomain, note: HEURISTIC_NOTE };
}

/** ENERGY — total "work" being generated by open findings, weighted by severity × confidence. */
export function computeEnergy(findings: Finding[]) {
  const totalEnergy = Math.round(findings.reduce((s, f) => s + f.sev * f.confidence, 0) * 10) / 10;
  const level = clamp(Math.round((totalEnergy / (findings.length * 5 || 1)) * 100), 0, 100);
  return { totalEnergy, level, note: HEURISTIC_NOTE };
}

/** INERTIA — organizational resistance to change; inverse of average |velocity|. */
export function computeInertia(domains: Domain[]) {
  const avgAbsV = avg(domains.map((d) => Math.abs(d.velocity)));
  const inertiaIndex = clamp(Math.round((1 - avgAbsV / 2.4) * 100), 0, 100);
  return { inertiaIndex, note: HEURISTIC_NOTE };
}

/** RESONANCE — domains whose velocity moves in sync, suggesting coupling. */
export function computeResonance(domains: Domain[]) {
  const pairs: { a: Domain; b: Domain; strength: number }[] = [];
  for (let i = 0; i < domains.length; i++) {
    for (let j = i + 1; j < domains.length; j++) {
      const a = domains[i];
      const b = domains[j];
      const sameSign = Math.sign(a.velocity) === Math.sign(b.velocity) && a.velocity !== 0;
      if (!sameSign) continue;
      const closeness = 1 - clamp(Math.abs(a.velocity - b.velocity) / 2.4, 0, 1);
      if (closeness > 0.55) pairs.push({ a, b, strength: Math.round(closeness * 100) / 100 });
    }
  }
  pairs.sort((x, y) => y.strength - x.strength);
  return { pairs, note: HEURISTIC_NOTE };
}

/** VELOCITY — fastest-moving domain, signed. */
export function fastestDomain(domains: Domain[]) {
  if (!domains.length) return null;
  return [...domains].sort((a, b) => Math.abs(b.velocity) - Math.abs(a.velocity))[0];
}

export function healthiestDomain(domains: Domain[]) {
  if (!domains.length) return null;
  return [...domains].sort((a, b) => b.score - a.score)[0];
}

export function projectScore(domain: Domain, daysAhead: number) {
  return clamp(Math.round((domain.score + (domain.velocity * daysAhead) / 7) * 10) / 10, 0, 10);
}

export function scoreAtDaysAgo(domain: Domain, daysAgo: number): number {
  if (!domain.history.length) return domain.score;
  let best = domain.history[0];
  for (const p of domain.history) {
    if (Math.abs(p.daysAgo - daysAgo) < Math.abs(best.daysAgo - daysAgo)) best = p;
  }
  return best.score;
}
