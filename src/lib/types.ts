export type EventType =
  | 'velocity.logged'
  | 'engagement.pulse'
  | 'feedback.given'
  | 'decision.logged'
  | 'decision.outcome'
  | 'conflict.logged'
  | 'hr.attrition.logged'
  | 'ops.incident.logged'
  | 'fin.pl.logged'
  | 'hr.pip.started'
  | 'hypothesis.generated'
  | 'hypothesis.result'
  | 'agent.executed'
  | 'agent.proposal.accepted'
  | 'agent.proposal.rejected';

export interface LeadosEvent {
  id: string;
  ts: string; // ISO timestamp
  type: EventType | string;
  data: Record<string, any>;
}

export interface Person {
  id: string;
  name: string;
  role: string;
  team: string;
}

export interface AppState {
  events: LeadosEvent[];
  roster: Person[];
  settings: Record<string, any>;
}

export type HypothesisType = 'causal' | 'predictive' | 'descriptive';
export type HypothesisOutcome = 'confirmed' | 'refuted' | 'inconclusive';

export interface HypothesisData {
  id: string;
  statement: string;
  type: HypothesisType;
  source: string;
  variables: { name: string; currentValue: number | string | null }[];
  prediction: string;
  testMetric: string;
  testWindow_days: number;
  confidenceAtGeneration: number;
  autoGenerated: boolean;
  label: string;
}

export type AuthorityLevel = 1 | 2 | 3;

export interface AgentTaskResult {
  task: string;
  status: 'COMPLETED' | 'ESCALATED' | 'ERROR' | 'QUEUED';
  authority: AuthorityLevel;
  result?: any;
  error?: string;
}

export type CognitiveLoadLevel = 'LOW' | 'MEDIUM' | 'HIGH';
