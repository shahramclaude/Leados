/**
 * app/core/domain/counterfactualRegistry.js — leaf vocabulary for the
 * Counterfactual Policy Terminal (Schema v76, ADR-0068).
 *
 * Leaf module with zero imports so `schema.js`, `counterfactualPolicy.js`,
 * `counterfactualPolicyRules.js`, `propagationContracts.js`, `csv.js` and
 * `insights.js` share one canonical vocabulary without circular dependencies.
 *
 * The question this terminal answers, and the only question it may answer:
 *   "Would a named, fully-specified alternative policy have scored better than
 *    the way I actually decided — and how much hidden bias would it take to
 *    explain the difference away?"
 *
 * Cross-domain foundations encoded in this vocabulary:
 *  - Dudík, Langford & Li (2011) doubly-robust off-policy evaluation: the
 *    value V(pi) of a target policy estimated from logged bandit feedback
 *    generated by a different behavioural policy. Estimators: direct method,
 *    inverse propensity scoring (Horvitz–Thompson 1952), self-normalised IPS
 *    (Hájek 1971 / Swaminathan & Joachims 2015) and the doubly-robust
 *    (Robins, Rotnitzky & Zhao 1994; Bang & Robins 2005) combination.
 *  - Manski (1990) partial identification: with no assumption on the
 *    counterfactual arm the identified set on a bounded reward is an interval,
 *    not a point. A sign is only claimed when the interval excludes zero.
 *  - Rosenbaum (2002) sensitivity analysis for hidden bias in matched pairs:
 *    a Gamma-bound on the odds of treatment assignment, reported as a design
 *    sensitivity — how much unobserved confounding would be needed to overturn
 *    the finding. Matched binary pairs reduce to McNemar (1947) with a
 *    bounded-binomial worst case (Rosenbaum 1987).
 *  - Howard, Ramdas, McAuliffe & Sekhon (2021) time-uniform confidence
 *    sequences: an interval valid at every stopping time, so a leader who
 *    checks this screen daily is not spending an unreported alpha.
 *  - VanderWeele & Ding (2017) E-value lineage: a point estimate from
 *    observational data is reported with the strength of confounding that
 *    would be needed to explain it, never as a causal effect.
 */

