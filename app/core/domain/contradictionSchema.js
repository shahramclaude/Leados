/**
 * app/core/domain/contradictionSchema.js — fail-closed normalizers for the
 * Cross-Line Contradiction Audit (ADR-0144, Schema v121).
 *
 * WHAT IS STORED
 * --------------
 * `lineMandates` — one row per DECLARED charter: this line, this objective, this
 * lever, this direction, this share of the scorecard, optionally this claim on an
 * existing budget envelope, optionally a declared target. Every field is a human
 * declaration; nothing is inferred from a goal's title, and a goal's numeric key
 * result is never re-read as a "direction" because a leader who wanted 30 from 40
 * may have wanted less of a bad thing or more of a good one.
 *
 * `contradictionReviews` — one row per RULED finding: which derived finding, the
 * verdict, the chief's own reasoning, the date it comes back, the named line
 * that must change when the verdict is a resequence, and POINTERS to the
 * decision and the obligation the rule issued. The finding itself is NOT stored.
 *
 * `contradictionMarkers` — RULE-CNT-01's idempotency ledger.
 *
 * WHAT IS NEVER STORED
 * --------------------
 *  - a finding, a severity, a contradiction count, a "conflict score", a queue
 *    multiplier or a person's weight total. Every one of those is DERIVED on
 *    read from the declarations plus the live matrix. A stored severity is a
 *    verdict waiting to disagree with the declarations it was computed from.
 *  - the finding's state (`undecided` etc.), which is re-derived from which
 *    reviews exist, so a hand-edited file cannot close a finding it never ruled
 *    on.
 *  - a copy of a goal, a budget, a delegation or a decision. The rows carry ids;
 *    whether the referenced record still exists, and in what state, is re-read
 *    from the real record on every render — a dangling pointer is PRINTED, never
 *    repaired into a plausible one.
 *
 * A malformed row is DROPPED with a printed warning, never repaired. An invented
 * charter is an invented accountability (ADR-0140's rule), and an invented
 * ruling is worse than an open question.
 *
 * ALL MONEY, WEIGHTS AND TARGETS ARE INTEGERS: basis points of 100%, or whole
 * percent, or the lever's declared unit. No float ever participates in a
 * comparison a leader will act on.
 */

import {
  CONTRADICTION_BOUNDS,
  CONTRADICTION_DEFAULTS,
  CONTRADICTION_DIRECTION_KEYS,
  CONTRADICTION_FINDING_KEYS,
  CONTRADICTION_FULL_BP,
  CONTRADICTION_LEVER_KEYS,
  CONTRADICTION_LIMITS,
  CONTRADICTION_VERDICT_KEYS,
} from './contradictionRegistry.js';

function isPlainObject(value) {
  return Boolean(value) && typeof value === 'object' && !Array.isArray(value);
}

function text(value, max = 300) {
  return typeof value === 'string' ? value.trim().slice(0, max) : '';
}

function id(value) {
  return typeof value === 'string' && /^[a-zA-Z0-9_-]{1,80}$/.test(value.trim()) ? value.trim() : null;
}

/** A finding key is generated by the engine and must round-trip unchanged. */
function findingKey(value) {
  return typeof value === 'string' && /^[a-z-]+\|[a-zA-Z0-9_|.:#~-]{1,240}$/.test(value.trim()) ? value.trim() : null;
}

function stamp(value) {
  const s = text(value, 40);
  if (!s) return null;
  const t = Date.parse(s);
  return Number.isFinite(t) ? new Date(t).toISOString() : null;
}

function day(value) {
  const s = text(value, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(s)) return null;
  const d = new Date(`${s}T00:00:00.000Z`);
  return Number.isFinite(d.getTime()) && d.toISOString().slice(0, 10) === s ? s : null;
}

function clampInt(value, bounds, fallback) {
  const n = Math.round(Number(value));
  if (!Number.isFinite(n)) return fallback;
  return Math.min(bounds.max, Math.max(bounds.min, n));
}

/**
 * A declared integer measurement. `null` is honest — nothing was declared — and
 * is never coerced to 0, because `Number(null) === 0` is precisely the defect
 * ADR-0136 had to repair: a missing figure read as a measured zero and quietly
 * won a comparison.
 */
function measurement(value, { min = 0, max = CONTRADICTION_LIMITS.targetMax } = {}) {
  if (value === null || value === undefined || value === '') return null;
  const n = Number(value);
  if (!Number.isFinite(n)) return null;
  const rounded = Math.round(n);
  if (rounded < min || rounded > max) return null;
  return rounded;
}

/** Basis points of 100%. Zero is a real declaration (a charter with no weight). */
function basisPoints(value) {
  if (value === null || value === undefined || value === '') return null;
  const n = Number(value);
  if (!Number.isFinite(n)) return null;
  const rounded = Math.round(n);
  if (rounded < 0 || rounded > CONTRADICTION_FULL_BP) return null;
  return rounded;
}

/* ---------------------------------------------------------------- settings */

/**
 * The four printed conventions. Every one is clamped to a declared bound and
 * falls back to the printed default; none is fitted from the record. A boolean
 * is only flipped by an explicit `false`, so a typo cannot switch propagation off
 * as a side effect.
 */
export function normalizeContradictionSettings(settings = {}, bounds = CONTRADICTION_BOUNDS, defaults = CONTRADICTION_DEFAULTS) {
  const raw = isPlainObject(settings) ? settings : {};
  const out = {};
  out.ctrAutoPropagate = raw.ctrAutoPropagate !== false;
  out.ctrUtilisationCeiling = clampInt(raw.ctrUtilisationCeiling, bounds.utilisationCeiling, defaults.ctrUtilisationCeiling);
  out.ctrMaterialityBp = clampInt(raw.ctrMaterialityBp, bounds.materialityBp, defaults.ctrMaterialityBp);
  out.ctrReviewDays = clampInt(raw.ctrReviewDays, bounds.reviewDays, defaults.ctrReviewDays);
  return out;
}

/* ----------------------------------------------------------------- mandates */

/**
 * One declared charter. Refused whole — with a printed reason — if the line, the
 * lever or the direction cannot be read, because a charter whose lever is
 * unknown is a promise the audit cannot reason about, and silently mapping it to
 * a neighbouring lever would manufacture a contradiction that nobody declared.
 */
function normalizeMandate(raw) {
  if (!isPlainObject(raw)) return { drop: 'not an object' };
  const mandateId = id(raw.id);
  const lineManagerId = id(raw.lineManagerId);
  const lever = CONTRADICTION_LEVER_KEYS.includes(raw.lever) ? raw.lever : null;
  const direction = CONTRADICTION_DIRECTION_KEYS.includes(raw.direction) ? raw.direction : null;
  if (!mandateId) return { drop: 'no readable id' };
  if (!lineManagerId) return { drop: 'no readable line manager' };
  if (!lever) return { drop: 'a lever outside the declared taxonomy' };
  if (!direction) return { drop: 'no declared direction' };
  const status = raw.status === 'withdrawn' ? 'withdrawn' : 'active';
  const effectiveFrom = day(raw.effectiveFrom);
  const effectiveTo = day(raw.effectiveTo);
  if (effectiveFrom && effectiveTo && effectiveTo < effectiveFrom) {
    return { drop: 'a window that ends before it starts' };
  }
  return {
    row: {
      id: mandateId,
      lineManagerId,
      // A pointer, never a copy. Whether the goal still exists is re-read on
      // every render and printed as `dangling-objective` when it does not.
      objectiveId: id(raw.objectiveId),
      lever,
      direction,
      // `null` = not declared. The engine refuses a weight total that depends on
      // it rather than reading the gap as zero.
      weightBp: basisPoints(raw.weightBp),
      // Declared integer in the lever's own unit (percent for utilisation).
      targetValue: measurement(raw.targetValue),
      // A claim on an EXISTING envelope. The ceiling lives on the budget record;
      // this row carries only the share it claims.
      envelopeId: id(raw.envelopeId),
      envelopeClaimBp: basisPoints(raw.envelopeClaimBp),
      effectiveFrom,
      effectiveTo,
      note: text(raw.note, CONTRADICTION_LIMITS.noteChars),
      status,
      withdrawnOn: status === 'withdrawn' ? day(raw.withdrawnOn) : null,
      withdrawReason: status === 'withdrawn' ? text(raw.withdrawReason, CONTRADICTION_LIMITS.reasonChars) : '',
      declaredOn: day(raw.declaredOn),
      declaredBySeatId: id(raw.declaredBySeatId),
      createdAt: stamp(raw.createdAt),
      updatedAt: stamp(raw.updatedAt),
    },
  };
}

export function normalizeLineMandates(raw, warnings = []) {
  const list = Array.isArray(raw) ? raw : [];
  if (raw !== undefined && raw !== null && !Array.isArray(raw)) {
    warnings.push('Contradiction audit: `lineMandates` was not a list; no charter was read.');
    return [];
  }
  const out = [];
  const seen = new Set();
  let dropped = 0;
  let duplicate = 0;
  for (const item of list.slice(0, CONTRADICTION_LIMITS.mandatesMax * 2)) {
    const result = normalizeMandate(item);
    if (result.drop) { dropped += 1; continue; }
    if (seen.has(result.row.id)) { duplicate += 1; continue; }
    seen.add(result.row.id);
    out.push(result.row);
  }
  if (dropped) {
    warnings.push(`Contradiction audit: dropped ${dropped} unreadable charter row(s) rather than guessing their lever or direction.`);
  }
  if (duplicate) {
    warnings.push(`Contradiction audit: dropped ${duplicate} duplicate charter id(s); the first row of each id was kept.`);
  }
  return out.slice(0, CONTRADICTION_LIMITS.mandatesMax);
}

/* ------------------------------------------------------------------ reviews */

function normalizeIssued(list) {
  if (!Array.isArray(list)) return [];
  return list
    .filter(isPlainObject)
    .map((entry) => ({
      taskId: id(entry.taskId),
      lineId: id(entry.lineId),
      dueOn: day(entry.dueOn),
    }))
    .filter((entry) => entry.taskId);
}

/**
 * One recorded ruling. Refused whole if its verdict or subject is unreadable, or
 * if a resequence does not name which line must change — a ruling that does not
 * say who must act is not a ruling, it is a note.
 */
function normalizeReview(raw) {
  if (!isPlainObject(raw)) return { drop: 'not an object' };
  const reviewId = id(raw.id);
  const key = findingKey(raw.findingKey);
  const kind = CONTRADICTION_FINDING_KEYS.includes(raw.kind) ? raw.kind : null;
  const verdict = CONTRADICTION_VERDICT_KEYS.includes(raw.verdict) ? raw.verdict : null;
  const rationale = text(raw.rationale, CONTRADICTION_LIMITS.rationaleChars);
  const decidedOn = day(raw.decidedOn);
  if (!reviewId) return { drop: 'no readable id' };
  if (!key) return { drop: 'no readable finding key' };
  if (!kind) return { drop: 'a finding kind outside the declared set' };
  if (!verdict) return { drop: 'no readable verdict' };
  if (!rationale) return { drop: 'no recorded reasoning' };
  if (!decidedOn) return { drop: 'no decision date' };

  const subjectType = raw.subjectType === 'person' ? 'person' : raw.subjectType === 'envelope' ? 'envelope' : 'lines';
  const lineAId = id(raw.lineAId);
  const lineBId = id(raw.lineBId);
  const personId = id(raw.personId);
  if (subjectType === 'person' && !personId) return { drop: 'a person-level ruling with no person' };
  if (subjectType !== 'person' && (!lineAId || !lineBId || lineAId === lineBId)) {
    return { drop: 'a line-pair ruling without two distinct lines' };
  }
  const resequenceLineId = id(raw.resequenceLineId);
  if (verdict === 'resequenced') {
    if (!resequenceLineId) return { drop: 'a resequence that names no line to change' };
    if (subjectType !== 'person' && resequenceLineId !== lineAId && resequenceLineId !== lineBId) {
      return { drop: 'a resequence naming a line that is not party to the finding' };
    }
  }

  return {
    row: {
      id: reviewId,
      findingKey: key,
      kind,
      subjectType,
      lineAId: subjectType === 'person' ? null : lineAId,
      lineBId: subjectType === 'person' ? null : lineBId,
      personId: subjectType === 'person' ? personId : null,
      lever: CONTRADICTION_LEVER_KEYS.includes(raw.lever) ? raw.lever : null,
      envelopeId: subjectType === 'envelope' ? id(raw.envelopeId) : null,
      verdict,
      rationale,
      decidedOn,
      decidedBySeatId: id(raw.decidedBySeatId),
      // A resequence always has a date it is looked at again; an acceptance may
      // declare one, and the engine prints the declared horizon when it does.
      reviewOn: day(raw.reviewOn),
      resequenceLineId: verdict === 'resequenced' ? resequenceLineId : null,
      decisionId: id(raw.decisionId),
      obligationIssued: normalizeIssued(raw.obligationIssued),
      createdAt: stamp(raw.createdAt),
    },
  };
}

export function normalizeContradictionReviews(raw, warnings = []) {
  const list = Array.isArray(raw) ? raw : [];
  if (raw !== undefined && raw !== null && !Array.isArray(raw)) {
    warnings.push('Contradiction audit: `contradictionReviews` was not a list; no ruling was read.');
    return [];
  }
  const out = [];
  const seen = new Set();
  let dropped = 0;
  let duplicate = 0;
  for (const item of list) {
    const result = normalizeReview(item);
    if (result.drop) { dropped += 1; continue; }
    if (seen.has(result.row.id)) { duplicate += 1; continue; }
    seen.add(result.row.id);
    out.push(result.row);
  }
  if (dropped) {
    warnings.push(`Contradiction audit: dropped ${dropped} unreadable review row(s) rather than reconstructing a ruling nobody recorded.`);
  }
  if (duplicate) {
    warnings.push(`Contradiction audit: dropped ${duplicate} duplicate review id(s); the first row of each id was kept.`);
  }
  return out;
}

/* ------------------------------------------------------------------ markers */

export function normalizeContradictionMarkers(raw) {
  if (!Array.isArray(raw)) return [];
  const out = [];
  const seen = new Set();
  for (const item of raw) {
    if (!isPlainObject(item)) continue;
    const key = text(item.key, 200);
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push({
      key,
      kind: text(item.kind, 40),
      summary: text(item.summary, 280),
      at: stamp(item.at),
    });
  }
  return out.slice(-CONTRADICTION_LIMITS.markers);
}

/* ------------------------------------------------------------- presentation */

/**
 * The default settings block, exported so the schema's SETTINGS_DEFAULTS and the
 * view render the same numbers. This is a declaration, not a computation.
 */
export function contradictionSettingsDefaults() {
  return normalizeContradictionSettings({});
}
