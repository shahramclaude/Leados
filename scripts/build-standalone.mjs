#!/usr/bin/env node
/**
 * scripts/build-standalone.mjs — produce ONE self-contained LeadOS HTML file.
 *
 * The canonical app is a zero-build set of native ES modules. That is ideal for
 * development, but browsers deliberately block `import './module.js'` from a
 * `file://` page because module scripts are fetched with CORS semantics and a
 * local file has an opaque origin (MDN; WHATWG issue #8121). A classic inline
 * script has no such fetch. Therefore this build-time tool:
 *
 *   1. bundles `app/standalone-entry.js` and its entire import graph into one IIFE with
 *      esbuild (build-time dependency only — the output has no npm modules),
 *   2. inlines `app/styles.css`,
 *   3. replaces the external `<script type="module">` and `<link>` with inline
 *      `<script>` / `<style>` tags,
 *   4. marks the page as standalone, gives it a separate localStorage key and
 *      adds a `connect-src 'none'` CSP so the copy cannot phone home,
 *   5. injects an honest portability banner: the APP travels in the file, the
 *      DATA does not — export JSON to move records to another PC.
 *
 * The generated file is meant to be double-clicked: no server, no folder of
 * assets, no install, no internet. It is committed for immediate use and can
 * be regenerated after any source change with `npm run build:standalone`.
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const outIndex = args.indexOf('--out');
const outArg = outIndex !== -1 ? args[outIndex + 1] : 'LeadOS-standalone.html';
const OUT = path.isAbsolute(outArg) ? outArg : path.resolve(ROOT, outArg);
const MINIFY = !args.includes('--no-minify');

if (!OUT.toLowerCase().endsWith('.html')) {
  throw new Error('The standalone output must be an .html file.');
}
if (OUT === path.join(ROOT, 'index.html')) {
  throw new Error('Refusing to overwrite the canonical index.html.');
}

function read(rel) {
  return fs.readFileSync(path.join(ROOT, rel), 'utf8');
}

function walkJs(dir) {
  const out = [];
  for (const entry of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
    const rel = path.posix.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walkJs(rel));
    else if (entry.name.endsWith('.js')) out.push(rel);
  }
  return out.sort();
}

function sourceFingerprint(files) {
  const hash = crypto.createHash('sha256');
  for (const rel of ['index.html', 'app/styles.css', ...files]) {
    hash.update(rel);
    hash.update('\0');
    hash.update(read(rel));
    hash.update('\0');
  }
  return hash.digest('hex');
}

function shortCommit() {
  try {
    return execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
      cwd: ROOT,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return 'unknown';
  }
}

function escapeForInlineScript(source) {
  // A literal </script> inside a JS string would close the inline script tag
  // early. Escaping the slash is semantically identical inside JS strings.
  return source.replace(/<\/script/gi, '<\\/script');
}

function escapeForInlineStyle(source) {
  return source.replace(/<\/style/gi, '<\\/style');
}

function replaceOnce(html, needle, replacement, label) {
  if (!html.includes(needle)) {
    throw new Error(`Standalone build could not find ${label} in index.html.`);
  }
  // A replacer function is essential: a minified bundle can contain `$&`,
  // which String.replace would otherwise expand back into the matched tag and
  // inject hundreds of phantom module-script strings into the output.
  return html.replace(needle, () => replacement);
}

const jsFiles = walkJs('app');
const fingerprint = sourceFingerprint(jsFiles);
const commit = shortCommit();
const schemaMatch = read('app/core/schema.js').match(/export const SCHEMA_VERSION = (\d+);/);
const schemaVersion = schemaMatch ? schemaMatch[1] : 'unknown';
const buildId = `${schemaVersion}.${commit}.${fingerprint.slice(0, 12)}`;

const result = await build({
  absWorkingDir: ROOT,
  entryPoints: ['app/standalone-entry.js'],
  bundle: true,
  write: false,
  outfile: 'LeadOS-standalone.bundle.js',
  format: 'iife',
  platform: 'browser',
  target: ['es2020'],
  minify: MINIFY,
  charset: 'utf8',
  legalComments: 'none',
  sourcemap: false,
  metafile: true,
  logLevel: 'silent',
  banner: {
    js: [
      '/* LeadOS standalone build — generated by scripts/build-standalone.mjs.',
      `   Schema v${schemaVersion} · source ${commit} · fingerprint ${fingerprint.slice(0, 16)}.`,
      '   All application modules are inlined; no network calls, no runtime dependencies. */',
    ].join('\n'),
  },
});

const bundle = escapeForInlineScript(result.outputFiles[0].text);
const css = escapeForInlineStyle(read('app/styles.css'));
let html = read('index.html');
const moduleCount = Object.keys(result.metafile?.inputs || {}).length;

html = replaceOnce(
  html,
  '<html lang="en">',
  '<html lang="en" data-leados-standalone="true">',
  'the <html> tag',
);

html = replaceOnce(
  html,
  '    <link rel="stylesheet" href="./app/styles.css" />',
  `    <style id="leados-inline-styles">\n${css}\n    </style>`,
  'the canonical stylesheet link',
);

const distributionMeta = [
  `    <meta name="leados-distribution" content="standalone-offline" />`,
  `    <meta name="leados-standalone-build" content="${buildId} · ${moduleCount} source modules · source sha256 ${fingerprint.slice(0, 16)}" />`,
  `    <meta http-equiv="Content-Security-Policy" content="connect-src 'none'; object-src 'none'; base-uri 'none'" />`,
].join('\n');
html = replaceOnce(html, '  </head>', `${distributionMeta}\n  </head>`, 'the </head> tag');

const banner = [
  '      <div class="standalone-banner banner banner-info" role="status" data-leados-standalone-banner="true">',
  '        <div class="banner-text">',
  '          <strong>Standalone offline copy</strong>',
  '          <p>This one HTML file contains the whole LeadOS app. It needs no server, install or internet. Your records are NOT embedded. When the browser allows local storage they stay in this browser profile; if it blocks local storage for local files, Settings says so and records are temporary. Export JSON before moving PCs or closing the tab, then import it after opening the copied file.</p>',
  '        </div>',
  '        <div class="banner-actions"><a class="btn btn-small btn-ghost" href="#/settings">Data &amp; export</a></div>',
  '      </div>',
].join('\n');
html = replaceOnce(html, '<div class="main">', `<div class="main">\n${banner}`, 'the main shell');

const bootstrap = [
  '    <script id="leados-standalone-bootstrap">',
  '      window.__LEADOS_STANDALONE__ = true;',
  "      window.__LEADOS_STORAGE_KEY__ = 'leados.standalone.v1';",
  `      window.__LEADOS_BUILD_ID__ = ${JSON.stringify(buildId)};`,
  '    </script>',
].join('\n');
const appScript = `    <script id="leados-standalone-app">\n${bundle}\n    </script>`;
html = replaceOnce(
  html,
  '    <script type="module" src="./app/main.js"></script>',
  `${bootstrap}\n${appScript}`,
  'the canonical module script',
);

// Hard invariants: the deliverable must not need any external resource to boot.
if (/<script[^>]+src=/i.test(html)) throw new Error('Standalone build still has an external script src.');
if (/<link[^>]+rel=["']stylesheet["']/i.test(html)) throw new Error('Standalone build still has an external stylesheet.');
if (/<script[^>]+type=["']module["']/i.test(html)) throw new Error('Standalone build still has a module script.');
if (/\bimport\s*\(/.test(bundle)) throw new Error('Standalone bundle still contains a dynamic import.');
if (/\bfetch\s*\(/.test(bundle)) throw new Error('Standalone bundle still contains fetch().');
if (/https?:\/\//i.test(css)) throw new Error('Standalone CSS still contains an external URL.');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, html, 'utf8');
const bytes = Buffer.byteLength(html, 'utf8');
console.log(`LeadOS standalone build written: ${OUT}`);
console.log(`  ${bytes.toLocaleString('en-US')} bytes · ${moduleCount} source modules · schema v${schemaVersion}`);
console.log(`  source ${commit} · sha256 ${fingerprint.slice(0, 16)} · minify ${MINIFY ? 'on' : 'off'}`);
console.log('  Double-click the .html file. No server, folder, install or network is required.');
