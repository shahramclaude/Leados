/**
 * Generates sdk.ts — a small, fully-typed fetch-based TypeScript client — from
 * the same route registry used for the OpenAPI spec. There is no hand-maintained
 * SDK in this repo: this file is the SDK, and it is always regenerated.
 *
 * Run with: npx tsx scripts/generate-sdk.ts
 */
import fs from "node:fs";
import path from "node:path";
import { routeRegistry } from "../src/lib/api/spec";

function toMethodName(operationId: string) {
  return operationId;
}

const lines: string[] = [];
lines.push("// AUTO-GENERATED by scripts/generate-sdk.ts — do not hand-edit. Run `npx tsx scripts/generate-sdk.ts`.");
lines.push("// Source of truth: src/lib/api/spec.ts (also used to generate api-spec.json/yaml and postman-collection.json).");
lines.push("");
lines.push("export type LeadosSdkOptions = {");
lines.push("  baseUrl?: string;");
lines.push("  apiKey: string;");
lines.push("  fetchImpl?: typeof fetch;");
lines.push("};");
lines.push("");
lines.push("export class LeadosApiError extends Error {");
lines.push("  code: string;");
lines.push("  status: number;");
lines.push("  correlationId?: string;");
lines.push("  details?: unknown;");
lines.push("  constructor(status: number, body: { error?: { code: string; message: string; correlationId?: string; details?: unknown } }) {");
lines.push("    super(body.error?.message ?? `Request failed with status ${status}`);");
lines.push("    this.status = status;");
lines.push("    this.code = body.error?.code ?? 'UNKNOWN';");
lines.push("    this.correlationId = body.error?.correlationId;");
lines.push("    this.details = body.error?.details;");
lines.push("  }");
lines.push("}");
lines.push("");
lines.push("export type ListPage<T> = { data: T[]; page: { cursor: string | null; hasMore: boolean; limit: number } };");
lines.push("");
lines.push("export class LeadosClient {");
lines.push("  private baseUrl: string;");
lines.push("  private apiKey: string;");
lines.push("  private fetchImpl: typeof fetch;");
lines.push("");
lines.push("  constructor(opts: LeadosSdkOptions) {");
lines.push("    this.baseUrl = (opts.baseUrl ?? '/api').replace(/\\/$/, '');");
lines.push("    this.apiKey = opts.apiKey;");
lines.push("    this.fetchImpl = opts.fetchImpl ?? fetch;");
lines.push("  }");
lines.push("");
lines.push("  /** Low-level request helper. Automatically attaches auth, parses JSON, and throws LeadosApiError on non-2xx. */");
lines.push("  async request<T>(method: string, path: string, opts: { query?: Record<string, string | undefined>; body?: unknown; idempotencyKey?: string; headers?: Record<string, string> } = {}): Promise<{ data: T; headers: Headers; status: number }> {");
lines.push("    const url = new URL(this.baseUrl + path, 'http://localhost');");
lines.push("    for (const [k, v] of Object.entries(opts.query ?? {})) if (v !== undefined) url.searchParams.set(k, v);");
lines.push("    const headers: Record<string, string> = { Authorization: `Bearer ${this.apiKey}`, ...opts.headers };");
lines.push("    if (opts.body !== undefined) headers['content-type'] = 'application/json';");
lines.push("    if (opts.idempotencyKey) headers['Idempotency-Key'] = opts.idempotencyKey;");
lines.push("    const res = await this.fetchImpl(url.pathname + url.search, { method, headers, body: opts.body !== undefined ? JSON.stringify(opts.body) : undefined });");
lines.push("    if (res.status === 204) return { data: undefined as T, headers: res.headers, status: res.status };");
lines.push("    const json = await res.json().catch(() => ({}));");
lines.push("    if (!res.ok) throw new LeadosApiError(res.status, json);");
lines.push("    return { data: json as T, headers: res.headers, status: res.status };");
lines.push("  }");
lines.push("");

for (const route of routeRegistry) {
  const name = toMethodName(route.operationId);
  const hasParams = !!route.params;
  const hasQuery = !!route.query;
  const hasBody = !!route.body;
  const jsPath = route.path.replace(/\{([a-zA-Z0-9_]+)\}/g, (_m, p) => `\${params.${p}}`);

  const argParts: string[] = [];
  if (hasParams) argParts.push("params: { id: string }");
  if (hasBody) argParts.push("body: Record<string, unknown>");
  if (hasQuery) argParts.push("query?: Record<string, string | undefined>");
  argParts.push("opts?: { idempotencyKey?: string }");

  lines.push(`  /** ${route.summary} */`);
  lines.push(`  async ${name}(${argParts.join(", ")}) {`);
  lines.push(
    `    return this.request(${JSON.stringify(route.method)}, \`${jsPath}\`, { ${[
      hasQuery ? "query" : null,
      hasBody ? "body" : null,
      "idempotencyKey: opts?.idempotencyKey",
    ]
      .filter(Boolean)
      .join(", ")} });`,
  );
  lines.push("  }");
  lines.push("");
}

lines.push("}");
lines.push("");
lines.push("export default LeadosClient;");

const out = lines.join("\n") + "\n";
fs.writeFileSync(path.resolve(__dirname, "../sdk.ts"), out);
console.log(`[api:gen] wrote sdk.ts with ${routeRegistry.length} methods.`);
